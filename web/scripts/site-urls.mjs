/**
 * One address per page (Imperion audit, November 18; owner's pick: clean
 * addresses, /about rather than /about.html).
 *
 * Root cause of "7 pages with one incoming internal link" and every page
 * crawled twice: the live site named each page by two addresses. The source,
 * the canonical tags and the sitemap said /about.html; Netlify's Pretty URLs
 * setting (dashboard only, nothing in the repo) rewrote every link to /about
 * at deploy; both addresses answered 200. A crawler credited the links to
 * /about and the page's own declarations to /about.html. Nothing in the repo
 * could see the split, because the rewrite happened after the build.
 *
 * Now the build does it, where tests can see it:
 * - every link to a page with a canonical tag, and every absolute URL of one
 *   (canonical, og:url, JSON-LD, sitemap), is written in its clean form;
 * - dist/_redirects sends each old .html address to the clean one (301,
 *   forced, because the .html file still exists; tested on a deploy preview,
 *   November 18: one hop, no loop);
 * - checkDist() fails the build if any page or file disagrees.
 *
 * The source keeps "about.html" links so pages still open from the file
 * system and on a plain local server. Pages without a canonical tag (the
 * booking page at /book, the print landing pages, 404) keep their addresses.
 * Links built by scripts at run time (funnel.js, script.js) still say .html
 * and reach the page through the 301.
 */
import fs from "node:fs";
import path from "node:path";

export const SITE = "https://513autoclean.com";

/** "about.html" -> "/about", "index.html" -> "/". */
export const cleanPath = (file) => (file === "index.html" ? "/" : "/" + file.replace(/\.html$/, ""));

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
// Attribute order doesn't matter: <link href=... rel="canonical"> counts too.
export const tagWith = (html, tag, attr) => [...html.matchAll(new RegExp(`<${tag}\\b[^>]*>`, "gi"))].map((m) => m[0]).find((t) => attr.test(t));
const canonicalOf = (html) => /\bhref="([^"]*)"/.exec(tagWith(html, "link", /\brel="canonical"/) ?? "")?.[1] ?? null;
const isNoindex = (html) => /\bcontent="[^"]*noindex/.test(tagWith(html, "meta", /\bname="robots"/) ?? "");

/** The pages that have their own address: every dist page with a canonical tag. */
export function cleanPages(dist) {
  return fs.readdirSync(dist).filter((f) => f.endsWith(".html") && canonicalOf(fs.readFileSync(path.join(dist, f), "utf8")) !== null).sort();
}

/** Rewrites links and absolute URLs that name a page by its .html file. */
export function cleanLinks(text, files) {
  const names = files.map((f) => esc(f.replace(/\.html$/, ""))).join("|");
  if (!names) return text;
  const clean = (name) => cleanPath(name + ".html");
  return text
    .replace(new RegExp(`(\\bhref=["'])(?:\\.?/)?(${names})\\.html(?=[#?"'])`, "g"), (_, a, n) => a + clean(n))
    .replace(new RegExp(`${esc(SITE)}/(${names})\\.html\\b`, "g"), (_, n) => SITE + clean(n));
}

/**
 * For stamp-assets.mjs: the pages whose links the build rewrites in dist/js,
 * read from the SOURCE pages (dist/ doesn't exist yet when it runs). A change
 * in this list changes every script's ?v= hash, so a cached script can never
 * keep links the build would now write differently.
 */
export function urlSalt(dir) {
  return "\0urls:" + cleanPages(dir).join(",");
}

/** Netlify _redirects: each old .html address to its clean one. */
export function redirectsFor(files) {
  return "# Generated by web/scripts/site-urls.mjs: the old .html address of each page, to its one address.\n" +
    files.map((f) => `/${f} ${cleanPath(f)} 301!`).join("\n") + "\n";
}

/** Rewrites every page, the sitemap and the scripts' HTML in dist/, and writes _redirects. */
/**
 * Pages, the sitemap, and the scripts: funnel.js and analytics.js build
 * links in HTML strings (Terms, Privacy, Contact), which visitors and
 * crawlers that run scripts see. Only href="..."-shaped strings are rewritten
 * there (which includes location.href = '...'); anything else, such as
 * script.js's map of old home-page sections, reaches the page through the 301. Rewriting dist/js changes a script without changing its
 * source, so stamp-assets.mjs folds the page list into the ?v= hash
 * (urlSalt), as it does for the phone number.
 */
export function publishedTextFiles(dist) {
  const js = fs.existsSync(path.join(dist, "js")) ? fs.readdirSync(path.join(dist, "js")).filter((x) => x.endsWith(".js")).map((x) => path.join("js", x)) : [];
  return [...fs.readdirSync(dist).filter((x) => /\.(html|xml|js)$/.test(x)), ...js];
}

export function applyCleanUrls(dist) {
  const files = cleanPages(dist);
  for (const f of publishedTextFiles(dist)) {
    const p = path.join(dist, f), before = fs.readFileSync(p, "utf8"), after = cleanLinks(before, files);
    if (after !== before) fs.writeFileSync(p, after);
  }
  fs.writeFileSync(path.join(dist, "_redirects"), redirectsFor(files));
  return files;
}

/**
 * Everything a crawler is told must agree. Returns a list of problems (empty
 * when the site is consistent); build-dist.mjs fails on any.
 */
export function checkDist(dist) {
  const problems = [];
  const files = cleanPages(dist);
  const html = Object.fromEntries(fs.readdirSync(dist).filter((f) => f.endsWith(".html")).map((f) => [f, fs.readFileSync(path.join(dist, f), "utf8")]));
  const sitemap = fs.readFileSync(path.join(dist, "sitemap.xml"), "utf8");
  const locs = [...sitemap.matchAll(/<loc>([^<]*)<\/loc>/g)].map((m) => m[1]);
  const redirects = fs.existsSync(path.join(dist, "_redirects")) ? fs.readFileSync(path.join(dist, "_redirects"), "utf8") : "";
  const stale = new RegExp(`(\\bhref=["'](?:\\.?/)?|${esc(SITE)}/)(${files.map((f) => esc(f)).join("|")})(?=[#?"'<\\s]|$)`, "m");
  // Any absolute address on this site that ends in .html must be a real page
  // without its own address (the print landing pages); book.html in the
  // structured data went to a 301, then a script, then /book.
  const absHtml = new RegExp(`${esc(SITE)}/([A-Za-z0-9._-]+\\.html)`, "g");

  for (const f of publishedTextFiles(dist).filter((x) => !x.endsWith(".html"))) {
    const text = fs.readFileSync(path.join(dist, f), "utf8");
    if (files.length && stale.test(text)) problems.push(`${f}: still names a page by its .html address (${stale.exec(text)[0]}...)`);
  }
  for (const [f, text] of [...Object.entries(html), ["sitemap.xml", sitemap]]) {
    for (const [, page] of text.matchAll(absHtml)) {
      if (!html[page] || files.includes(page)) problems.push(`${f}: ${SITE}/${page} is not an address a visitor should be sent to`);
    }
  }
  for (const [f, text] of Object.entries(html)) {
    const h1 = (text.match(/<h1[\s>]/g) ?? []).length;
    if (h1 !== 1) problems.push(`${f}: ${h1} <h1> headings (a page needs exactly one)`);
    if (files.length && stale.test(text)) problems.push(`${f}: still names a page by its .html address (${stale.exec(text)[0]}...)`);
    if (!files.includes(f) && !isNoindex(text)) problems.push(`${f}: no canonical tag and no noindex, so search engines get no address for it`);
  }
  for (const f of files) {
    const want = SITE + cleanPath(f);
    if (canonicalOf(html[f]) !== want) problems.push(`${f}: canonical is ${canonicalOf(html[f])}, not ${want}`);
    const listed = locs.includes(want);
    if (isNoindex(html[f]) && listed) problems.push(`${f}: noindex, but listed in sitemap.xml`);
    if (!isNoindex(html[f]) && !listed) problems.push(`${f}: indexable, but missing from sitemap.xml`);
    if (!redirects.includes(`/${f} ${cleanPath(f)} 301!`)) problems.push(`${f}: no redirect from /${f} in _redirects`);
  }
  for (const loc of locs) if (!files.some((f) => SITE + cleanPath(f) === loc)) problems.push(`sitemap.xml: ${loc} is not the address of any page`);

  // Semrush flags a page that only one other page links to. The main pages
  // are in the header and footer of every page; a new city or service page is
  // linked only from what its generator links it from, so check that before
  // it can go live (MIN_LINKERS other indexable pages).
  const indexable = files.filter((f) => !isNoindex(html[f]));
  const linkers = Object.fromEntries(indexable.map((f) => [cleanPath(f), new Set()]));
  for (const f of indexable) {
    for (const [, href] of html[f].matchAll(/\bhref=["']([^"']*)["']/g)) {
      const to = linkTarget(href);
      if (to && to !== cleanPath(f) && linkers[to]) linkers[to].add(f);
    }
  }
  for (const f of indexable) {
    if (f === "index.html") continue;
    const n = linkers[cleanPath(f)].size;
    if (n < MIN_LINKERS) problems.push(`${f}: linked from ${n} other page${n === 1 ? "" : "s"}; a published page needs links from at least ${MIN_LINKERS}`);
  }
  return problems;
}

export const MIN_LINKERS = 2;

/** The clean path a link points to on this site ("/about"), or null. */
function linkTarget(href) {
  if (/^(mailto:|tel:|sms:|#|javascript:)/.test(href)) return null;
  if (/^https?:/.test(href) && !href.startsWith(SITE)) return null;
  const p = href.replace(SITE, "").replace(/[#?].*$/, "");
  return p === "" ? null : p.startsWith("/") ? p : "/" + p;
}
